def overlay(fname, crop, scale=1):
    rgb = Image.fromarray(np.stack([im] * 3, -1)).convert('RGB'); dr = ImageDraw.Draw(rgb)
    colors = {'0': (255, 0, 0), '1.30': (255, 140, 0), '1.0': (0, 160, 0), '0.60': (0, 0, 255), '0.631': (255, 0, 255),
              '0.70': (0, 170, 170)}
    for k, pp in pts.items():
        col = colors[k.rstrip('rst') if k not in colors else k]
        for p in pp:
            x, y = px(p[0]), py(p[1]); dr.ellipse((x - 2, y - 2, x + 2, y + 2), outline=col)
    c = rgb.crop(crop); c.resize((c.size[0] * scale, c.size[1] * scale), Image.LANCZOS).save(fname)

